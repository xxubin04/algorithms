SELECT SALES_DATE,
        PRODUCT_ID,
        USER_ID,
        SALES_AMOUNT
FROM ONLINE_SALE
WHERE DATE_FORMAT(SALES_DATE, "%Y-%m-%d") >= '2022-03-01'
    AND DATE_FORMAT(SALES_DATE, "%Y-%m-%d") < '2022-04-01'

UNION ALL

SELECT SALES_DATE,
        PRODUCT_ID,
        NULL,
        SALES_AMOUNT
FROM OFFLINE_SALE
WHERE DATE_FORMAT(SALES_DATE, "%Y-%m-%d") >= '2022-03-01'
    AND DATE_FORMAT(SALES_DATE, "%Y-%m-%d") < '2022-04-01'
ORDER BY SALES_DATE ASC, PRODUCT_ID ASC, USER_ID ASC















