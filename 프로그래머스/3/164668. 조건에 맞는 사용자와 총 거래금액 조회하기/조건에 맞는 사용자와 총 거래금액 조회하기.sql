WITH TRADE AS (
    SELECT B.WRITER_ID,
            U.NICKNAME,
            SUM(B.PRICE) AS TOTAL_PRICE
    FROM USED_GOODS_BOARD B
    JOIN USED_GOODS_USER U
    ON B.WRITER_ID = U.USER_ID
    WHERE B.STATUS = 'DONE'
    GROUP BY B.WRITER_ID  
    HAVING TOTAL_PRICE >= 700000
)


SELECT WRITER_ID,
        NICKNAME,
        TOTAL_PRICE
FROM TRADE
ORDER BY TOTAL_PRICE