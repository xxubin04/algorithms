WITH MAX_LENGTH AS (
    SELECT FISH_TYPE, MAX(LENGTH) AS MAX_LENGTH
    FROM FISH_INFO
    GROUP BY FISH_TYPE
    ORDER BY ID
)




SELECT I.ID,
        N.FISH_NAME,
        I.LENGTH
FROM FISH_INFO I
JOIN FISH_NAME_INFO N
ON I.FISH_TYPE = N.FISH_TYPE
JOIN MAX_LENGTH M
ON I.FISH_TYPE = M.FISH_TYPE
WHERE I.LENGTH = M.MAX_LENGTH
ORDER BY I.ID
