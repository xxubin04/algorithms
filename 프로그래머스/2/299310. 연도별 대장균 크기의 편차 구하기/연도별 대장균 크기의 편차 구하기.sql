WITH MAX_ECOLI AS (
    SELECT YEAR(DIFFERENTIATION_DATE) AS YEAR,
            MAX(SIZE_OF_COLONY) AS MAX_SIZE
    FROM ECOLI_DATA
    GROUP BY YEAR 
    ORDER BY YEAR 
)


SELECT M.YEAR,
        M.MAX_SIZE - E.SIZE_OF_COLONY AS YEAR_DEV,
        E.ID
FROM ECOLI_DATA E
JOIN MAX_ECOLI M
ON YEAR(E.DIFFERENTIATION_DATE) = M.YEAR
ORDER BY YEAR, YEAR_DEV


