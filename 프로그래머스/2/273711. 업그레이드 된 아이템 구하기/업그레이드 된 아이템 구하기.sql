SELECT T.ITEM_ID,
        II.ITEM_NAME,
        II.RARITY
FROM ITEM_INFO I
JOIN ITEM_TREE T
ON I.ITEM_ID = T.PARENT_ITEM_ID
JOIN ITEM_INFO II
ON T.ITEM_ID = II.ITEM_ID
WHERE I.RARITY = 'RARE'
ORDER BY T.ITEM_ID DESC

